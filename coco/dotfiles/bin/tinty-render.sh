#!/usr/bin/env bash
# tinty-render — regenerate every themed config from the palette that tinty
# exports into the environment, then live-reload the running consumers.
#
# Run as tinty's apply/init hook (see coco/home/theme.nix). This is the single
# source of truth for how a base16/base24 scheme maps onto each app. It is a
# plain dotfile so theming can be tweaked without a rebuild; the Nix wrapper
# only supplies PATH (procps/dconf/tmux).
#
# Palette-driven consumers (kitty, waybar, lazygit, fuzzel, nvim) track any
# scheme; delta/tmux/gtk follow the light/dark variant only.
set -u

cfg="${XDG_CONFIG_HOME:-$HOME/.config}"
dotfiles="$HOME/dots/coco/dotfiles"

# Assemble base00..base0F as "rrggbb" (no leading #) from tinty's per-channel
# hex env vars, e.g. TINTY_SCHEME_PALETTE_BASE0A_HEX_{R,G,B}.
declare -A c
for k in 00 01 02 03 04 05 06 07 08 09 0A 0B 0C 0D 0E 0F; do
  r="TINTY_SCHEME_PALETTE_BASE${k}_HEX_R"
  g="TINTY_SCHEME_PALETTE_BASE${k}_HEX_G"
  b="TINTY_SCHEME_PALETTE_BASE${k}_HEX_B"
  c[$k]="${!r:-}${!g:-}${!b:-}"
done

variant="${TINTY_SCHEME_VARIANT:-dark}"
[ "$variant" = "light" ] || variant="dark"

# Write stdin to a file atomically, replacing whatever is there — including a
# stale symlink into the read-only nix store (left by the pre-tinty setup),
# which a plain `> file` redirect can't overwrite.
write_file() {
  local dest="$1" tmp
  tmp="$(mktemp "$dest.XXXXXX")"
  cat > "$tmp"
  mv -f "$tmp" "$dest"
}

# --- kitty: swap the included theme and live-reload every instance ----------
mkdir -p "$cfg/kitty"
write_file "$cfg/kitty/theme-active.conf" <<EOF
# Generated by tinty-render from the active base16/base24 scheme.
background            #${c[00]}
foreground            #${c[05]}
selection_background  #${c[05]}
selection_foreground  #${c[00]}
cursor                #${c[05]}
cursor_text_color     #${c[00]}
url_color             #${c[0D]}

color0  #${c[00]}
color1  #${c[08]}
color2  #${c[0B]}
color3  #${c[0A]}
color4  #${c[0D]}
color5  #${c[0E]}
color6  #${c[0C]}
color7  #${c[05]}
color8  #${c[03]}
color9  #${c[08]}
color10 #${c[0B]}
color11 #${c[0A]}
color12 #${c[0D]}
color13 #${c[0E]}
color14 #${c[0C]}
color15 #${c[07]}
color16 #${c[09]}
color17 #${c[0F]}
color18 #${c[01]}
color19 #${c[02]}
color20 #${c[04]}
color21 #${c[06]}
EOF
pkill -USR1 kitty 2>/dev/null || true

# --- waybar: swap the imported colours and reload the stylesheet ------------
mkdir -p "$cfg/waybar"
write_file "$cfg/waybar/colors-active.css" <<EOF
/* Generated by tinty-render from the active base16/base24 scheme. */
@define-color fg            #${c[05]};
@define-color surface       #${c[01]};
@define-color hover         #${c[02]};
@define-color focused       #${c[03]};
@define-color focused_hover #${c[04]};
@define-color accent        #${c[0A]};
@define-color warning       #${c[09]};
@define-color critical      #${c[08]};
@define-color critical_fg   #${c[00]};
@define-color network       #${c[0D]};
EOF
# waybar crashes on a SIGUSR2 reload (a GTK gtk_box_reorder_child assertion),
# so restart its user service instead — deterministic, re-reads the new CSS,
# no crash. Debounced: a burst of rapid applies (e.g. browsing themes in the
# fzf picker) collapses into a single restart after the last one.
pidf="${XDG_RUNTIME_DIR:-/tmp}/tinty-waybar-reload.pid"
[ -f "$pidf" ] && kill "$(cat "$pidf" 2>/dev/null)" 2>/dev/null || true
( sleep 0.4; systemctl --user restart waybar 2>/dev/null || true ) &
echo $! > "$pidf"

# --- lazygit: rewrite the whole config; next launch reads the new theme -----
mkdir -p "$cfg/lazygit"
write_file "$cfg/lazygit/config.yml" <<EOF
# Generated by tinty-render from the active base16/base24 scheme.
gui:
  theme:
    activeBorderColor:
      - "#${c[09]}"
      - bold
    inactiveBorderColor:
      - "#${c[03]}"
    searchingActiveBorderColor:
      - "#${c[0A]}"
      - bold
    optionsTextColor:
      - "#${c[0D]}"
    selectedLineBgColor:
      - "#${c[01]}"
    inactiveViewSelectedLineBgColor:
      - "#${c[02]}"
    selectedRangeBgColor:
      - "#${c[01]}"
    cherryPickedCommitFgColor:
      - "#${c[0D]}"
    cherryPickedCommitBgColor:
      - "#${c[0C]}"
    markedBaseCommitFgColor:
      - "#${c[0D]}"
    markedBaseCommitBgColor:
      - "#${c[0A]}"
    unstagedChangesColor:
      - "#${c[08]}"
    defaultFgColor:
      - "#${c[05]}"
EOF

# --- fuzzel: rewrite the config; the wrapper reads it per-launch ------------
mkdir -p "$cfg/fuzzel"
write_file "$cfg/fuzzel/fuzzel-active.ini" <<EOF
# Generated by tinty-render from the active base16/base24 scheme.
[main]
font=IosevkaTerm Nerd Font Mono:size=18
dpi-aware=yes
prompt=" > "
icon-theme=Mint-Y-Sand
terminal=kitty

[colors]
background=${c[00]}ff
text=${c[05]}ff
match=${c[0A]}ff
selection=${c[02]}ff
selection-text=${c[07]}ff
selection-match=${c[0A]}ff
border=${c[0A]}ff

[border]
width=2
radius=0
EOF

# --- nvim: write the active palette; running instances poll and re-apply ----
write_file "$cfg/nvim-theme-active.lua" <<EOF
-- Generated by tinty-render; polled by init.lua for live re-theming.
return {
  variant = "${variant}",
  palette = { base00 = "#${c[00]}", base01 = "#${c[01]}", base02 = "#${c[02]}", base03 = "#${c[03]}", base04 = "#${c[04]}", base05 = "#${c[05]}", base06 = "#${c[06]}", base07 = "#${c[07]}", base08 = "#${c[08]}", base09 = "#${c[09]}", base0A = "#${c[0A]}", base0B = "#${c[0B]}", base0C = "#${c[0C]}", base0D = "#${c[0D]}", base0E = "#${c[0E]}", base0F = "#${c[0F]}" },
}
EOF

# --- variant-only consumers -------------------------------------------------
# delta (git pager): git re-reads config per invocation, so no reload needed.
mkdir -p "$cfg/delta"
ln -sf "$dotfiles/config/delta/delta-$variant.gitconfig" "$cfg/delta/theme-active.gitconfig"

# GTK / portal-aware apps follow the variant via the color-scheme gsetting.
if [ "$variant" = "dark" ]; then
  scheme="prefer-dark"; gtk="Gruvbox-Dark"
else
  scheme="prefer-light"; gtk="Gruvbox-Light"
fi
dconf write /org/gnome/desktop/interface/color-scheme "'$scheme'" 2>/dev/null || true
dconf write /org/gnome/desktop/interface/gtk-theme "'$gtk'" 2>/dev/null || true

# tmux: re-theme every running server via the gruvbox plugin.
if tmux list-sessions >/dev/null 2>&1; then
  tmux set -g @tmux-gruvbox "$variant"
  tmux run-shell "$HOME/.tmux/plugins/tmux-gruvbox/gruvbox-tpm.tmux" 2>/dev/null || true
fi
